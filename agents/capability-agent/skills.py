"""Deterministic A2A skills over a capability report. No LLM is involved here."""
from __future__ import annotations

import hashlib
import json
import re
from typing import Any

from hcl_eval import UNKNOWN, evaluate

PLACEHOLDER = {"score": "<generated by Score>", "secret": "<from Kubernetes Secret>", "generated": "<generated>"}


def _entrypoints(report: dict[str, Any]) -> list[tuple[dict[str, Any], dict[str, Any] | None]]:
    pairs = []
    for capability in report["capabilities"]:
        entries = capability.get("score", {}).get("entrypoints")
        if not entries and not capability["terraform"]["resources"]:
            continue  # a shared helper module (e.g. access-lists: only locals and outputs) is not a deployable capability
        entries = entries or [None]
        pairs.extend((capability, entry) for entry in entries)
    return pairs


def _source(parameter: dict[str, Any], entry: dict[str, Any] | None) -> dict[str, Any]:
    for source in parameter.get("score_sources", []):
        if entry and source["provisioner"] == entry["uri"]:
            return source
    return {"set_by": "developer", "score_param": parameter["terraform_variable"]} if entry is None else {"set_by": "missing"}


def _developer_params(capability: dict[str, Any], entry: dict[str, Any] | None) -> list[dict[str, Any]]:
    params = []
    for parameter in capability["parameters"]:
        source = _source(parameter, entry)
        if source["set_by"] == "developer":
            params.append({
                "name": source["score_param"],
                "terraform_variable": parameter["terraform_variable"],
                "type": parameter["type"],
                "default": source.get("default", parameter["terraform_default"]),
                **({"effect": parameter["effect"]} if parameter.get("effect") else {}),
            })
    return params


def _slug(value: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", value.lower()).strip("_")


def _json_schema_type(tf_type: str) -> str | None:
    base = tf_type.split("(")[0].strip()
    return {"string": "string", "number": "number", "bool": "boolean", "list": "array", "set": "array",
            "tuple": "array", "map": "object", "object": "object"}.get(base)


def _tool_name(capability: dict[str, Any], entry: dict[str, Any] | None) -> tuple[str, str]:
    provider = _slug(entry["score_class"]) if entry else "terraform"
    return provider, f"provision_{_slug(entry['score_type'] if entry else capability['id'])}"


WORKLOAD_SCHEMA = {"type": "string", "pattern": "^[a-z0-9]([a-z0-9-]{0,38}[a-z0-9])?$",
                   "description": "Score workload name (metadata.name): lowercase letters, digits and hyphens, "
                                  "2-40 characters. Requests for the same workload update its resource."}
IMAGE_SCHEMA = {"type": "string", "pattern": "^[A-Za-z0-9._/:@-]+$",
                "description": "Container image of the workload, e.g. nginx:latest."}
REGIONS = ["us-east-1", "us-east-2", "us-west-1", "us-west-2"]
# Values score-api's /cgi-bin/score accepts (its allowlists are lowercase and case-sensitive).
SCORE_API_ALLOWED = {
    "environment": ["dev", "staging", "uat", "dr", "prod"],
    "instance_class": ["db.t3.micro", "db.t3.small", "db.t3.medium", "db.t4g.micro", "db.t4g.small"],
    "region": REGIONS,
    "plane": ["resource", "dev", "observability", "integration", "security", "unspecified"],
}
STORAGE_GB_RANGE = (1, 20)
PLANES = SCORE_API_ALLOWED["plane"]
ENVIRONMENTS = SCORE_API_ALLOWED["environment"]

# Score types score-api can execute, and what each needs besides the crawled params.
#   endpoint: score-api CGI endpoint; fields: request fields that are not Score params;
#   allowed: lowercase allowlists enforced before the call.
SCORE_TYPES: dict[str, dict[str, Any]] = {
    "postgres": {"endpoint": "score", "fields": ["workload", "image"], "allowed": SCORE_API_ALLOWED},
    # EKS: the module's own variable validations cover region, CIDRs and node sizes.
    # "inputs": the only params a user supplies; every other provisioner param keeps its platform default and is
    # neither advertised nor accepted. "require": inputs that are required although the module gives them a default.
    # enable_network_access (score-api default true) also creates the bastion, load balancer controller, NGINX and
    # NLB in the same request, fed from the cluster's outputs; bastion_access_mode picks ssm or ssh for that bastion.
    "eks": {"endpoint": "eks", "fields": ["workload"],
            "allowed": {"environment": ENVIRONMENTS, "plane": PLANES, "bastion_access_mode": ["ssm", "ssh"],
                        "ingress_nlb_scheme": ["internet-facing", "internal"]},
            # ingress_nlb_scheme internal: a private NLB, reached through a tunnel to the bastion's forwarder
            # (the stack's ingress_tunnel_command output).
            "inputs": ["cluster_name", "aws_account_id", "region", "kubernetes_version", "environment",
                       "enable_network_access", "bastion_access_mode", "ingress_nlb_scheme"],
            # What score-api applies when the input is left out (the provisioner's own default differs so that
            # clusters requested before bundling keep their shape when re-rendered).
            "defaults": {"enable_network_access": True}},
    # SSM bastion into an EKS VPC, requested separately from the cluster; the module validates the rest.
    # public_subnet_id is needed only with bastion_access_mode "ssh"; ssh_key_name defaults to "platform-bastion".
    "network-access": {"endpoint": "network-access", "fields": ["workload"],
                       "allowed": {"environment": ENVIRONMENTS, "plane": PLANES, "bastion_access_mode": ["ssm", "ssh"]},
                       "inputs": ["name", "aws_account_id", "region", "environment", "cluster_name", "vpc_id", "vpc_cidr", "subnet_id",
                                  "cluster_security_group_id", "bastion_access_mode", "ssh_key_name", "public_subnet_id"],
                       "require": ["cluster_security_group_id"],
                       "when": {("bastion_access_mode", "ssh"): ["public_subnet_id"]}},
}
# The modules' own can(regex(...)) validations, checked before score-api and advertised as schema patterns so forms
# can validate too. Keep in step with score-tf-modules variables.tf.
_ID = "[0-9a-f]{8,17}$"
INPUT_PATTERNS = {
    "eks": {"cluster_name": "^[a-z][a-z0-9-]{1,26}[a-z0-9]$", "aws_account_id": "^[0-9]{12}$",
            "region": "^[a-z]{2}(-gov)?-[a-z]+-[0-9]$", "kubernetes_version": "^1[.][0-9]{2}$"},
    "network-access": {"name": "^[a-z][a-z0-9-]{1,38}[a-z0-9]$", "cluster_name": "^[a-z][a-z0-9-]{1,26}[a-z0-9]$",
                       "aws_account_id": "^[0-9]{12}$", "region": "^[a-z]{2}(-gov)?-[a-z]+-[0-9]$",
                       "vpc_id": "^vpc-" + _ID, "subnet_id": "^subnet-" + _ID, "public_subnet_id": "^subnet-" + _ID,
                       "cluster_security_group_id": "^sg-" + _ID,
                       "vpc_cidr": "^([0-9]{1,3}[.]){3}[0-9]{1,3}/([0-9]|[12][0-9]|3[0-2])$",
                       "ssh_key_name": "^[A-Za-z0-9._-]{1,255}$"},
}
# Status filters: the prefix of each capability's Terraform CR names.
CAPABILITIES = ["rds", "eks", "network-access"]
EXECUTABLE_SCORE_TYPES = set(SCORE_TYPES)
FIELD_SCHEMAS = {"workload": WORKLOAD_SCHEMA, "image": IMAGE_SCHEMA}


